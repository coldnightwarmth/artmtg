import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "cardnft");
const SOURCE_PATH = path.join(OUT_DIR, "cardnft-source.json");
const DATA_PATH = path.join(OUT_DIR, "cardnft-data.js");
const TRAITS_PATH = path.join(OUT_DIR, "cardnft-traits.js");
const METADATA_DIR = path.join(OUT_DIR, "assets", "metadata");

const WORKERS = Number(process.env.CARDNFT_METADATA_WORKERS || 32);
const LIMIT = Number(process.env.CARDNFT_METADATA_LIMIT || 0);
const RETRIES = Number(process.env.CARDNFT_METADATA_RETRIES || 4);

const { CARD_NFTS } = await import(`${pathToFileURL(DATA_PATH).href}?t=${Date.now()}`);
const source = JSON.parse(await readFile(SOURCE_PATH, "utf8"));
const mintSource = new Map((source.mints || []).map((mint) => [mint.onchainId, mint]));

const entries = (LIMIT > 0 ? CARD_NFTS.slice(0, LIMIT) : CARD_NFTS).map((card, index) => {
  const sourceMint = mintSource.get(card.mint);
  const metadataFile = metadataFileForCard(card);
  return {
    card,
    index,
    metadataUri: sourceMint?.metadataUri,
    metadataFile,
    outputPath: path.join(OUT_DIR, metadataFile),
  };
});

await mkdir(METADATA_DIR, { recursive: true });
await fetchMetadata(entries);
await writeTraitsModule(CARD_NFTS);

console.log(`Done: ${entries.length} CardNFT metadata JSONs synced.`);

async function fetchMetadata(items) {
  const queue = items.filter((entry) => entry.metadataUri);
  let completed = items.length - queue.length;
  let failed = 0;

  async function runWorker(workerIndex) {
    while (queue.length) {
      const entry = queue.shift();
      await mkdir(path.dirname(entry.outputPath), { recursive: true });

      if (await exists(entry.outputPath)) {
        completed += 1;
        if (completed % 250 === 0 || completed === items.length) {
          console.log(`Metadata ${completed}/${items.length} (${failed} failed)`);
        }
        continue;
      }

      try {
        const metadata = await retry(
          () => fetchJson(entry.metadataUri),
          RETRIES,
          `metadata ${entry.card.title}`,
        );
        await writeFile(entry.outputPath, `${JSON.stringify(metadata, null, 2)}\n`);
      } catch (error) {
        failed += 1;
        console.warn(`Worker ${workerIndex} failed ${entry.card.title}: ${error.message}`);
      }

      completed += 1;
      if (completed % 100 === 0 || completed === items.length) {
        console.log(`Metadata ${completed}/${items.length} (${failed} failed)`);
      }
    }
  }

  await Promise.all(
    Array.from({ length: Math.min(WORKERS, Math.max(1, queue.length)) }, (_, index) => runWorker(index + 1)),
  );
}

async function writeTraitsModule(cards) {
  const categories = [];
  const categorySet = new Set();
  const rows = [];

  for (const card of cards) {
    const metadataFile = metadataFileForCard(card);
    const metadataPath = path.join(OUT_DIR, metadataFile);
    let metadata = null;
    try {
      metadata = JSON.parse(await readFile(metadataPath, "utf8"));
    } catch {
      // Missing metadata leaves an empty trait row so CARD_NFTS alignment is preserved.
    }

    const traitMap = new Map();
    for (const attribute of metadata?.attributes || []) {
      const type = cleanTraitText(attribute?.trait_type);
      if (!type) continue;
      if (!categorySet.has(type)) {
        categorySet.add(type);
        categories.push(type);
      }
      traitMap.set(type, cleanTraitText(attribute?.value));
    }

    rows.push({
      metadata: metadataFile,
      traitMap,
    });
  }

  categories.sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));

  const publicRows = rows.map((row) => ({
    metadata: row.metadata,
    values: categories.map((category) => row.traitMap.get(category) || ""),
  }));

  const moduleText = [
    "// Generated by scripts/sync-cardnft-metadata.mjs",
    `export const CARD_NFT_TRAIT_CATEGORIES = ${JSON.stringify(categories, null, 2)};`,
    `export const CARD_NFT_TRAITS = ${JSON.stringify(publicRows, null, 2)};`,
    "",
  ].join("\n");
  await writeFile(TRAITS_PATH, moduleText);
}

async function fetchJson(url) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 30000);
  let response;
  try {
    response = await fetch(url, {
      headers: { accept: "application/json,*/*;q=0.8" },
      signal: controller.signal,
    });
  } finally {
    clearTimeout(timeout);
  }

  if (!response.ok) {
    throw new Error(`metadata fetch failed ${response.status}`);
  }
  return response.json();
}

async function retry(task, tries, label) {
  let lastError;
  for (let attempt = 1; attempt <= Math.max(1, tries); attempt += 1) {
    try {
      return await task();
    } catch (error) {
      lastError = error;
      if (attempt < tries) await wait(450 * attempt);
    }
  }
  throw new Error(`${label} failed after ${tries} attempts: ${lastError?.message || lastError}`);
}

function metadataFileForCard(card) {
  const imageDirectory = path.posix.dirname(card.file);
  const baseName = path.posix.basename(card.file, path.posix.extname(card.file));
  return imageDirectory.replace("assets/cards", "assets/metadata") + `/${baseName}.json`;
}

function cleanTraitText(value) {
  return String(value ?? "").trim();
}

async function exists(filePath) {
  try {
    const fileStat = await stat(filePath);
    return fileStat.isFile() && fileStat.size > 0;
  } catch {
    return false;
  }
}

function wait(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
