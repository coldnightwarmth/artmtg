import { execFile } from "node:child_process";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import { CARD_NFTS } from "../cardnft-data.js";

const execFileAsync = promisify(execFile);
const ROOT = process.cwd();
const OUT_PATH = path.join(ROOT, "cardnft-owners.js");
const ALCHEMY_DAS_URL = "https://solana-mainnet.g.alchemy.com/v2/docs-demo";
const COLLECTION_GROUP = process.env.CARDNFT_COLLECTION_GROUP || "HpGDYGz6aRUs5qbvp1dmWGKTicQctX4PixfcouAQDCHF";
const PAGE_LIMIT = Number(process.env.CARDNFT_OWNER_PAGE_LIMIT || 500);
const PAGE_DELAY_MS = Number(process.env.CARDNFT_OWNER_PAGE_DELAY_MS || 750);
const RETRIES = Number(process.env.CARDNFT_OWNER_RETRIES || 4);
const REQUEST_TIMEOUT_MS = Number(process.env.CARDNFT_OWNER_REQUEST_TIMEOUT_MS || 15000);

const CARD_INDEX_BY_MINT = new Map(CARD_NFTS
  .map((card, index) => [String(card?.mint || "").trim(), index])
  .filter(([mint]) => mint));

const owners = new Map();
let matched = 0;
let pageNumber = 1;

while (true) {
  const result = await alchemyDas("getAssetsByGroup", {
    groupKey: "collection",
    groupValue: COLLECTION_GROUP,
    limit: PAGE_LIMIT,
    page: pageNumber,
    options: {
      showCollectionMetadata: false,
      showFungible: false,
      showUnverifiedCollections: true,
      showZeroBalance: false,
    },
  });
  const page = Array.isArray(result?.items) ? result.items : [];

  for (const asset of page) {
    const index = CARD_INDEX_BY_MINT.get(String(asset?.id || "").trim());
    const owner = String(asset?.ownership?.owner || "").trim();
    if (!Number.isInteger(index) || !owner) continue;

    if (!owners.has(owner)) owners.set(owner, []);
    owners.get(owner).push(index);
    matched += 1;
  }

  console.log(`Fetched ${page.length} collection assets on page ${pageNumber}; matched ${matched}.`);
  if (page.length < PAGE_LIMIT) break;

  pageNumber += 1;
  await wait(PAGE_DELAY_MS);
}

const ownerSnapshot = {};
for (const [owner, indexes] of [...owners.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  ownerSnapshot[owner] = [...new Set(indexes)].sort((a, b) => a - b);
}

const moduleText = [
  "// Generated by scripts/sync-cardnft-owners.mjs",
  `export const CARD_NFT_OWNER_SNAPSHOT = ${JSON.stringify({
    fetchedAt: new Date().toISOString(),
    collectionGroup: COLLECTION_GROUP,
    owners: ownerSnapshot,
  }, null, 2)};`,
  "",
].join("\n");

await writeFile(OUT_PATH, moduleText);
console.log(`Done: wrote ${owners.size} owners and ${matched} card ownership records.`);

async function alchemyDas(method, params) {
  let lastError;
  for (let attempt = 1; attempt <= Math.max(1, RETRIES); attempt += 1) {
    console.log(`Requesting Alchemy DAS ${method} page ${params.page} (attempt ${attempt}/${RETRIES})`);
    const response = await curlJson(ALCHEMY_DAS_URL, {
      jsonrpc: "2.0",
      id: `${method}-${params.page}`,
      method,
      params,
    }).catch((error) => {
      lastError = error;
      return null;
    });

    if (!response) {
      if (attempt < RETRIES) {
        await wait(PAGE_DELAY_MS * attempt);
        continue;
      }
      break;
    }

    console.log(`Alchemy DAS responded ${response.status} for ${method} page ${params.page}`);
    if (response.ok && !response.body?.error) return response.body?.result;

    lastError = new Error(response.body?.error?.message || `Alchemy DAS API failed: ${response.status}`);
    if (attempt < RETRIES && (response.status === 429 || response.status >= 500 || response.body?.error)) {
      const waitMs = response.status === 429 ? 60000 : PAGE_DELAY_MS * attempt;
      console.log(`Waiting ${Math.round(waitMs / 1000)}s before retrying.`);
      await wait(waitMs);
      continue;
    }

    break;
  }

  throw lastError;
}

async function curlJson(url, requestBody) {
  const { stdout } = await execFileAsync("curl", [
    "-sS",
    "-L",
    "--max-time",
    String(Math.ceil(REQUEST_TIMEOUT_MS / 1000)),
    "-H",
    "accept: application/json",
    "-H",
    "content-type: application/json",
    "-H",
    "origin: https://www.alchemy.com",
    "-H",
    "referer: https://www.alchemy.com/",
    "--data",
    JSON.stringify(requestBody),
    "-w",
    "\n__HTTP_STATUS__:%{http_code}\n",
    url,
  ], {
    maxBuffer: 20 * 1024 * 1024,
    timeout: REQUEST_TIMEOUT_MS + 3000,
  });
  const match = stdout.match(/\n__HTTP_STATUS__:(\d+)\n$/);
  if (!match) throw new Error("curl response did not include a status code");

  const status = Number(match[1]);
  const bodyText = stdout.slice(0, match.index).trim();
  let responseBody = null;
  if (bodyText) {
    try {
      responseBody = JSON.parse(bodyText);
    } catch {
      responseBody = bodyText;
    }
  }

  return { ok: status >= 200 && status < 300, status, body: responseBody };
}

function wait(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
